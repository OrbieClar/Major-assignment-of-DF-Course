BACKGROUND=[
"土方堆积、开挖和地形监测需要比较不同时间获取的点云。两期点云既可能存在坐标或测站位姿引起的整体错位，也可能具有真实的局部高程变化。直接计算高差会将两类因素混合；先配准再比较虽然能够降低整体错位，但拟合所用点集的选择会影响后续体积。",
"迭代最近点算法（ICP）通过重复建立最近邻对应和估计刚性变换实现局部配准[1]。在两期存在真实变化时，变化点参与同一刚性拟合可能使估计变换偏向变化区域。拟合残差下降不必然等于正确位姿误差下降，也不直接保证高程积分正确。若面积为A的区域残留近似均匀高程偏差δh，则其净体积偏差近似为Aδh，例如1000 m²区域的1 mm偏差即可对应约1 m³体积差。",
"已有研究已从选点、匹配、加权及剔除等环节改造ICP，并研究法向空间采样[2]；截尾ICP通过降低大残差点对的影响处理部分对应异常[3]；稳健损失和迭代重加权也是成熟思路[5]。因此，使用法向、残差阈值或稳健统计本身不能直接作为新增技术的证明。",
"稳定区域识别与配准的结合也已有研究。Yang与Schwieger的工作结合超体素与变形点云稳定区域识别，py4dgeo官方教程列出其出处并强调需要已有初始对齐[4,6]。公开文本CN122384746A还描述了稳定置信度、加权配准与形变估计的反馈关系[8]。本课程尚未完成上述超体素方法在同一地形基准上的可靠复现，不能进行未经实施的胜负比较。",
"本方案解决的具体困难是：在不输入变化位置、人工稳定区和正确位姿的条件下，自动构建用于刚性拟合的参考点集；同时使被排除的变化点保留在输出中供高差和体积计算使用。针对这一困难，在普通点到点ICP前后增加一次基于双向法向残差的筛选，并明确回退与有效网格规则。相对全点ICP的流程改造在本文具体公开，但尚不据此判断相对于全部现有技术的专利新颖性。"]

