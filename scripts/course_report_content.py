TITLE="一种基于法向残差筛选的点云配准与体积估计方法"

ABSTRACT=("本方案涉及地形点云处理，提供一种基于法向残差筛选的点云配准与体积估计方法。两期点云统一坐标后执行初步配准，估计参考地形法向和点间距，构造双向法向残差，利用中位数及带尺度下限的MAD阈值筛选两期候选稳定参考点，并在保留点充分时精配准，不足时返回初步变换。最终变换作用于完整待测点云以保留真实变化；对共同有效网格内的高差进行面积积分，输出净变化体积。该流程用于减少局部真实变化对全点刚性拟合的干扰，适用于已有初始对齐且可用单值高程描述的地形。摘要附图为图1。")

